package tools

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// generatedFileGuardEnv 是「禁止编辑生成文件」的独立门控变量。
// 默认未设置或不为 1 时守卫完全不执行，编辑路径逐字节不变。
const generatedFileGuardEnv = "ARGENT_BLOCK_GENERATED_EDITS"

func generatedFileGuardEnabled() bool {
	return strings.TrimSpace(os.Getenv(generatedFileGuardEnv)) == "1"
}

// generatedNamePatterns 是常见的生成文件命名模式。按文件名（basename）匹配，
// 不对路径做大小写折叠以外的任何解释，避免误伤用户手工文件。
var generatedNamePatterns = []string{
	"zz_generated.*",
	"*.pb.go",
	"*.gen.ts",
	"*_pb2.py",
	"*.swagger.json",
	"*.gen.go",
}

// generatedHeaderMarkers 是生成文件头部常见的标记（在正文前 1024 字节内查找）。
var generatedHeaderMarkers = []string{
	"@generated",
	"Code generated",
	"DO NOT EDIT",
	"Autogenerated",
}

const generatedHeaderScanBytes = 1024

// checkGeneratedFile 在 opt-in 开启时拒绝编辑生成文件。content 是目标文件在
// 磁盘上的当前字节（新建文件传 nil）；文件名或头部任一命中即返回模型可读的
// 拒绝文案，指引改源文件后重新生成。关闭时直接返回 nil。
func checkGeneratedFile(path string, content []byte) error {
	if !generatedFileGuardEnabled() || path == "" {
		return nil
	}
	name := filepath.Base(path)
	for _, pattern := range generatedNamePatterns {
		if matched, _ := filepath.Match(pattern, name); matched {
			return generatedFileError(name, "文件名")
		}
	}
	limit := len(content)
	if limit > generatedHeaderScanBytes {
		limit = generatedHeaderScanBytes
	}
	head := string(content[:limit])
	for _, marker := range generatedHeaderMarkers {
		if strings.Contains(head, marker) {
			return generatedFileError(name, "头部标记 "+marker)
		}
	}
	return nil
}

func generatedFileError(name, evidence string) error {
	return fmt.Errorf("edit rejected: %s is a generated file (%s); edit the source and regenerate instead of editing the generated output", name, evidence)
}
