package tools

import (
	"context"
	"encoding/json"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func TestGeneratedGuardRejectsGeneratedFiles(t *testing.T) {
	root := t.TempDir()
	t.Setenv(generatedFileGuardEnv, "1")

	cases := []struct {
		name    string
		content string
	}{
		{"zz_generated.go", "package main\n"},
		{"api.pb.go", "package main\n"},
		{"schema.gen.ts", "export const x = 1;\n"},
		{"manual.go", "// Code generated by foo. DO NOT EDIT.\npackage main\n"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			path := filepath.Join(root, tc.name)
			if err := os.WriteFile(path, []byte(tc.content), 0o644); err != nil {
				t.Fatal(err)
			}
			err := checkGeneratedFile(path, []byte(tc.content))
			if err == nil {
				t.Fatalf("expected generated file %s to be rejected", tc.name)
			}
			if !strings.Contains(err.Error(), "generated") || !strings.Contains(err.Error(), "regenerate") {
				t.Fatalf("error missing guidance: %v", err)
			}
		})
	}
}

func TestGeneratedGuardAllowsManualFiles(t *testing.T) {
	root := t.TempDir()
	t.Setenv(generatedFileGuardEnv, "1")
	path := filepath.Join(root, "manual.go")
	content := []byte("package main\n// hand written\n")
	if err := os.WriteFile(path, content, 0o644); err != nil {
		t.Fatal(err)
	}
	if err := checkGeneratedFile(path, content); err != nil {
		t.Fatalf("manual file rejected: %v", err)
	}
}

func TestGeneratedGuardOffIsNoop(t *testing.T) {
	t.Setenv(generatedFileGuardEnv, "")
	path := filepath.Join(t.TempDir(), "zz_generated.go")
	if err := checkGeneratedFile(path, []byte("// Code generated DO NOT EDIT.\n")); err != nil {
		t.Fatalf("guard off should be no-op: %v", err)
	}
}

func TestGeneratedGuardWiredIntoWriteAndEdit(t *testing.T) {
	root := t.TempDir()
	t.Setenv(generatedFileGuardEnv, "1")
	path := filepath.Join(root, "api.pb.go")
	if err := os.WriteFile(path, []byte("old\n"), 0o644); err != nil {
		t.Fatal(err)
	}

	writeRaw, _ := json.Marshal(map[string]any{"path": "api.pb.go", "content": "new\n"})
	if _, err := (writeTool{}).Run(context.Background(), root, writeRaw); err == nil {
		t.Fatal("write should be rejected")
	}
	editRaw, _ := json.Marshal(map[string]any{"path": "api.pb.go", "old": "old", "new": "new"})
	if _, err := (editTool{}).Run(context.Background(), root, editRaw); err == nil {
		t.Fatal("edit should be rejected")
	}
	data, _ := os.ReadFile(path)
	if string(data) != "old\n" {
		t.Fatalf("file was modified despite guard: %q", data)
	}
}
