package eval

import (
	"bytes"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"
	"testing"
	"unicode/utf8"
)

// 本文件是 golden 快照的"守卫的守卫"：它不运行任何场景，也不改动快照内容，
// 只把 TestGoldenScenarios 赖以逐字节比对的几个前置条件固化下来。
// 一旦有人误把前两行英文注释中文化、改动 tools 列表顺序、删掉场景，
// 或让行尾符/编码发生漂移，这些测试会先于（或独立于）golden 比对变红。

const (
	// goldenHeaderLine1/2 是快照的前两行英文注释，属于快照内容本身。
	// TestGoldenScenarios 逐字节比对整份文件，因此这两行绝不能被中文化或改写。
	goldenHeaderLine1 = "# Golden snapshot for an eval scenario (generated by TestGoldenScenarios)."
	goldenHeaderLine2 = "# Refresh with: ARGENT_UPDATE_GOLDEN=1 go test ./internal/eval -run TestGoldenScenarios -count=1"
)

// goldenExpectedTools 锁定每个 golden 文件中 tools 行的成员及顺序。
// 这里记录的是快照里实际出现的工具（read/write 等）；bash/powershell 的注册顺序
// 由 internal/tools 的注册测试守护，并不出现在这批 golden 快照中。
// 合并 internal/bash 后，脚本化事件的字节序列必须保持不变，故顺序被显式钉死。
var goldenExpectedTools = map[string][]string{
	"answers_a_simple_question.golden":            {},
	"reads_a_file_before_answering.golden":        {"read"},
	"a_write_needs_approval_and_then_runs.golden": {"write"},
	"a_denied_path_is_refused_by_policy.golden":   {"read"},
	"a_read_feeds_a_write_in_one_run.golden":      {"read", "write"},
}

// goldenExpectedScenarioNames 锁定 TestGoldenScenarios 选取的场景名与数量，
// 防止误删或重排场景导致覆盖 silently 缩小。顺序与 golden_test.go 保持一致。
var goldenExpectedScenarioNames = []string{
	"answers a simple question",
	"reads a file before answering",
	"a write needs approval and then runs",
	"a denied path is refused by policy",
	"a read feeds a write in one run",
}

// readGoldenBytes 读取一个 golden 文件的原始字节。
func readGoldenBytes(t *testing.T, file string) []byte {
	t.Helper()
	data, err := os.ReadFile(filepath.Join(goldenDir, file))
	if err != nil {
		t.Fatalf("read golden %s: %v", file, err)
	}
	return data
}

// findGoldenToolsLine 从快照正文中取出 tools: 行。
func findGoldenToolsLine(t *testing.T, file string, data []byte) string {
	t.Helper()
	for _, line := range strings.Split(string(data), "\n") {
		if strings.HasPrefix(line, "tools: ") {
			return line
		}
	}
	t.Fatalf("golden %s has no tools: line", file)
	return ""
}

// parseGoldenTools 解析形如 tools: ["read" "write"] 的行，保留成员顺序。
func parseGoldenTools(t *testing.T, file, line string) []string {
	t.Helper()
	const prefix = "tools: "
	body := strings.TrimPrefix(line, prefix)
	if body == "[]" {
		return []string{}
	}
	if len(body) < 2 || body[0] != '[' || body[len(body)-1] != ']' {
		t.Fatalf("golden %s: malformed tools line %q", file, line)
	}
	fields := strings.Fields(body[1 : len(body)-1])
	tools := make([]string, 0, len(fields))
	for _, field := range fields {
		name, err := strconv.Unquote(field)
		if err != nil {
			t.Fatalf("golden %s: bad tool token %q in %q: %v", file, field, line, err)
		}
		tools = append(tools, name)
	}
	return tools
}

// TestGoldenFileSetLocked 锁定 golden 目录中的文件集合，防止新增/遗漏快照
// 让守卫形同虚设。数量与场景数量一致（当前为 5）。
func TestGoldenFileSetLocked(t *testing.T) {
	matches, err := filepath.Glob(filepath.Join(goldenDir, "*.golden"))
	if err != nil {
		t.Fatalf("glob golden dir: %v", err)
	}
	got := make([]string, 0, len(matches))
	for _, match := range matches {
		got = append(got, filepath.Base(match))
	}
	slices.Sort(got)

	want := make([]string, 0, len(goldenExpectedTools))
	for file := range goldenExpectedTools {
		want = append(want, file)
	}
	slices.Sort(want)

	if !slices.Equal(got, want) {
		t.Fatalf("golden file set drifted:\n got: %q\nwant: %q", got, want)
	}
}

// TestGoldenHeadersAreByteExact 锁定前两行英文注释逐字节不变。
// 只要有人把注释中文化（哪怕一个字节），这里就会先于 golden 比对失败。
func TestGoldenHeadersAreByteExact(t *testing.T) {
	for file := range goldenExpectedTools {
		t.Run(file, func(t *testing.T) {
			data := readGoldenBytes(t, file)
			lines := bytes.Split(data, []byte("\n"))
			if len(lines) < 2 {
				t.Fatalf("golden %s: fewer than 2 lines", file)
			}
			if got := string(lines[0]); got != goldenHeaderLine1 {
				t.Errorf("golden %s line 1 changed:\n got: %q\nwant: %q", file, got, goldenHeaderLine1)
			}
			if got := string(lines[1]); got != goldenHeaderLine2 {
				t.Errorf("golden %s line 2 changed:\n got: %q\nwant: %q", file, got, goldenHeaderLine2)
			}
		})
	}
}

// TestGoldenToolsListAndOrder 从 golden 解析 tools 行，断言工具列表与顺序未漂移。
func TestGoldenToolsListAndOrder(t *testing.T) {
	for file, want := range goldenExpectedTools {
		t.Run(file, func(t *testing.T) {
			data := readGoldenBytes(t, file)
			line := findGoldenToolsLine(t, file, data)
			got := parseGoldenTools(t, file, line)
			if !slices.Equal(got, want) {
				t.Errorf("golden %s tools drifted:\n got: %q\nwant: %q", file, got, want)
			}
		})
	}
}

// TestGoldenScenarioNamesLocked 锁定 TestGoldenScenarios 的场景名与数量。
func TestGoldenScenarioNamesLocked(t *testing.T) {
	if len(goldenScenarios) != len(goldenExpectedScenarioNames) {
		t.Fatalf("golden scenario count drifted: got %d, want %d",
			len(goldenScenarios), len(goldenExpectedScenarioNames))
	}
	got := make([]string, 0, len(goldenScenarios))
	for _, entry := range goldenScenarios {
		got = append(got, entry.name)
	}
	if !slices.Equal(got, goldenExpectedScenarioNames) {
		t.Fatalf("golden scenario names/order drifted:\n got: %q\nwant: %q",
			got, goldenExpectedScenarioNames)
	}
}

// TestGoldenFilesEncoding 断言所有 golden 文件均为合法 UTF-8 且无 CRLF，
// 避免行尾符/编码漂移让 TestGoldenScenarios 的逐字节比对意外变红。
func TestGoldenFilesEncoding(t *testing.T) {
	for file := range goldenExpectedTools {
		t.Run(file, func(t *testing.T) {
			data := readGoldenBytes(t, file)
			if !utf8.Valid(data) {
				t.Errorf("golden %s is not valid UTF-8", file)
			}
			if bytes.Contains(data, []byte("\r")) {
				t.Errorf("golden %s contains CR (CRLF drift)", file)
			}
			if bytes.HasPrefix(data, []byte("\xef\xbb\xbf")) {
				t.Errorf("golden %s contains a UTF-8 BOM", file)
			}
		})
	}
}
