var goldenScenarios = []struct {
	name string // scenario name in core.json
	file string // golden file name under testdata/golden
}{
	{"answers a simple question", "answers_a_simple_question.golden"},
	{"reads a file before answering", "reads_a_file_before_answering.golden"},
	{"a write needs approval and then runs", "a_write_needs_approval_and_then_runs.golden"},
	{"a denied path is refused by policy", "a_denied_path_is_refused_by_policy.golden"},
	{"a read feeds a write in one run", "a_read_feeds_a_write_in_one_run.golden"},
}

const goldenDir = "testdata/golden"

// updateGolden 报告调用方是否要求重新生成快照。
// 使用环境变量而非标志，使 `go test` 的标志保持
// 使 go test ./internal/eval 保持其通常行为。
func updateGolden() bool {
	v := os.Getenv("ARGENT_UPDATE_GOLDEN")
	return v != "" && v != "0" && v != "false"
}

func goldenPath(file string) string { return filepath.Join(goldenDir, file) }

// TestGoldenScenarios 通过脚本化循环运行每个选定场景并
// TestGoldenScenarios 通过脚本化循环运行每个选定场景，并将其规范化输出与提交的 golden 文件比较。不匹配时
// 打印行级 diff。设置 ARGENT_UPDATE_GOLDEN=1 可重写快照。
func TestGoldenScenarios(t *testing.T) {
	scenarios := loadCore(t)
	byName := make(map[string]Scenario, len(scenarios))
	for _, scenario := range scenarios {
		byName[scenario.Name] = scenario
	}

	update := updateGolden()
	if update {
		if err := os.MkdirAll(goldenDir, 0o755); err != nil {
			t.Fatalf("create golden dir: %v", err)
		}
	}

	for _, entry := range goldenScenarios {
		t.Run(entry.name, func(t *testing.T) {
			scenario, ok := byName[entry.name]
			if !ok {
				t.Fatalf("core.json has no scenario %q", entry.name)
			}

			// runOne 对场景评分并返回可观察结果：
			// 工具事件序列、最终助手文本、轮数、
			// 停止标志以及通过/原因结果。对这些脚本化场景它是完全确定的。
			result := runOne(context.Background(), 1, scenario, fakeRun, Options{})
			got := formatGolden(result)
			path := goldenPath(entry.file)

			if update {
				if err := os.WriteFile(path, []byte(got), 0o644); err != nil {
					t.Fatalf("write golden %s: %v", path, err)
				}
				t.Logf("updated golden %s", path)
				return
			}

			want, err := os.ReadFile(path)
			if err != nil {
				t.Fatalf("read golden %s: %v (run with ARGENT_UPDATE_GOLDEN=1 to create it)", path, err)
			}
			if string(want) != got {
				t.Errorf("golden mismatch for %q\n%s\nexpected file: %s",
					entry.name, diffText(string(want), got), path)
			}
		})
	}
}

// formatGolden 将 Result 渲染为稳定、易读的快照。格式是面向行的，使行为变化产生可读的 diff。
// 格式面向行，使行为变化产生可读的 diff。
// 末尾的助手文本原样保留（这些脚本只包含
// 末尾的助手文本原样保留（这些脚本只包含短的单行 ASCII 答案），放在显式分隔符内。
func formatGolden(result Result) string {
	var b strings.Builder
	b.WriteString("# Golden snapshot for an eval scenario (generated by TestGoldenScenarios).\n")
	b.WriteString("# Refresh with: ARGENT_UPDATE_GOLDEN=1 go test ./internal/eval -run TestGoldenScenarios -count=1\n")
	fmt.Fprintf(&b, "name: %s\n", result.Name)
	fmt.Fprintf(&b, "tools: %s\n", formatList(result.Tools))
	fmt.Fprintf(&b, "turns: %d\n", result.Turns)
	fmt.Fprintf(&b, "stopped: %t\n", result.Stopped)
	fmt.Fprintf(&b, "passed: %t\n", result.Passed)
	fmt.Fprintf(&b, "reason: %q\n", result.Reason)
	b.WriteString("--- text begin ---\n")
	b.WriteString(result.Text)
	if !strings.HasSuffix(result.Text, "\n") {
		b.WriteString("\n")
	}
	b.WriteString("--- text end ---\n")
	return b.String()
}

func formatList(items []string) string {
	if len(items) == 0 {
		return "[]"
	}
	parts := make([]string, len(items))
	for i, item := range items {
		parts[i] = strconv.Quote(item)
	}
	return "[" + strings.Join(parts, " ") + "]"
}

// diffText 生成一个小的统一风格行 diff 作为不匹配提示。
// 它使用 LCS，使未变化的上下文行对齐而非全部偏移。
func diffText(want, got string) string {
	wantLines := strings.Split(strings.TrimSuffix(want, "\n"), "\n")
	gotLines := strings.Split(strings.TrimSuffix(got, "\n"), "\n")
	n, m := len(wantLines), len(gotLines)

	lcs := make([][]int, n+1)
	for i := range lcs {
		lcs[i] = make([]int, m+1)
	}
	for i := n - 1; i >= 0; i-- {
		for j := m - 1; j >= 0; j-- {
			if wantLines[i] == gotLines[j] {
				lcs[i][j] = lcs[i+1][j+1] + 1
			} else if lcs[i+1][j] >= lcs[i][j+1] {
				lcs[i][j] = lcs[i+1][j]
			} else {
				lcs[i][j] = lcs[i][j+1]
			}
		}
	}

	var b strings.Builder
	b.WriteString("--- golden (expected)\n+++ actual\n")
	i, j := 0, 0
	for i < n && j < m {
		switch {
		case wantLines[i] == gotLines[j]:
			b.WriteString("  " + wantLines[i] + "\n")
			i++
			j++
		case lcs[i+1][j] >= lcs[i][j+1]:
			b.WriteString("- " + wantLines[i] + "\n")
			i++
		default:
			b.WriteString("+ " + gotLines[j] + "\n")
			j++
		}
	}
	for ; i < n; i++ {
		b.WriteString("- " + wantLines[i] + "\n")
	}
	for ; j < m; j++ {
		b.WriteString("+ " + gotLines[j] + "\n")
	}
	return b.String()
}
