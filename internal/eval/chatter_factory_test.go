// recordingChatter 是注入接缝用的假真实 provider：它记录每次请求到达以及请求内容，
// 并按 texts 顺序返回回复（耗尽后返回固定文本）。它不实现 Scripted 的 Calls/Violations，
// 因此会走 runOne 的计数包装器路径。
type recordingChatter struct {
	mu       sync.Mutex
	calls    int
	texts    []string
	requests [][]llm.Message
}

var _ llm.Chatter = (*recordingChatter)(nil)

func (r *recordingChatter) Chat(ctx context.Context, _ string, messages []llm.Message, _ []llm.ToolSpec, onText func(string)) (llm.Message, error) {
	if err := ctx.Err(); err != nil {
		return llm.Message{}, err
	}
	r.mu.Lock()
	index := r.calls
	r.calls++
	r.requests = append(r.requests, append([]llm.Message(nil), messages...))
	r.mu.Unlock()

	text := "live reply"
	if len(r.texts) > 0 {
		text = r.texts[len(r.texts)-1]
		if index < len(r.texts) {
			text = r.texts[index]
		}
	}
	emit(onText, text)
	return llm.Message{Role: "assistant", Content: text}, nil
}

func (r *recordingChatter) CallCount() int {
	r.mu.Lock()
	defer r.mu.Unlock()
	return r.calls
}

func (r *recordingChatter) RequestCount() int {
	r.mu.Lock()
	defer r.mu.Unlock()
	return len(r.requests)
}

// TestRunOneNilFactoryMatchesBaseline 冻结默认（nil）路径的可观察输出：
// 它必须与脚本化基线逐字节一致，注入接缝不得改变任何旧场景。
func TestRunOneNilFactoryMatchesBaseline(t *testing.T) {
	scenario := Scenario{
		Name:     "baseline",
		Prompt:   "answer",
		Provider: []ScriptTurn{{Respond: Respond{Text: "baseline answer"}}},
		Expect:   Expect{TextContains: []string{"baseline"}, Turns: intPtr(1)},
	}
	got := formatGolden(runOne(context.Background(), 1, scenario, fakeRun, Options{}))
	want := `# Golden snapshot for an eval scenario (generated by TestGoldenScenarios).
# Refresh with: ARGENT_UPDATE_GOLDEN=1 go test ./internal/eval -run TestGoldenScenarios -count=1
name: baseline
tools: []
turns: 1
stopped: false
passed: true
reason: ""
--- text begin ---
baseline answer
--- text end ---
`
	if got != want {
		t.Errorf("default (nil factory) output drifted from baseline:\n got:\n%s\nwant:\n%s\n%s", got, want, diffText(want, got))
	}
}

// TestRunOneUsesInjectedChatterFactory 断言注入的 Chatter 真正收到请求：
// 脚本化的 Provider 被忽略，备用文本来自工厂返回的假真实 provider。
func TestRunOneUsesInjectedChatterFactory(t *testing.T) {
	scenario := Scenario{
		Name:     "live",
		Prompt:   "hello live provider",
		Provider: []ScriptTurn{{Respond: Respond{Text: "should be ignored"}}},
		Expect:   Expect{TextContains: []string{"live"}, Turns: intPtr(1)},
	}
	chatter := &recordingChatter{texts: []string{"live reply"}}
	factoryCalled := 0
	opts := Options{ChatterFactory: func(s Scenario) llm.Chatter {
		factoryCalled++
		if s.Name != "live" {
			t.Errorf("factory got scenario %q, want %q", s.Name, "live")
		}
		return chatter
	}}

	result := runOne(context.Background(), 1, scenario, fakeRun, opts)
	if factoryCalled != 1 {
		t.Fatalf("factory called %d times, want 1", factoryCalled)
	}
	if result.Text != "live reply" {
		t.Fatalf("text = %q, want the injected chatter's reply", result.Text)
	}
	if strings.Contains(result.Text, "should be ignored") {
		t.Fatalf("the scripted provider leaked into the injected run: %q", result.Text)
	}
	if chatter.CallCount() != 1 || chatter.RequestCount() != 1 {
		t.Fatalf("injected chatter calls=%d requests=%d, want 1/1", chatter.CallCount(), chatter.RequestCount())
	}

	// 请求必须携带场景的 user prompt，证明请求真的到达了注入的 provider。
	r := chatter.requests[0]
	arrived := false
	for _, message := range r {
		if message.Role == "user" && message.Content == "hello live provider" {
			arrived = true
		}
	}
	if !arrived {
		t.Fatalf("the injected chatter did not see the user prompt: %+v", r)
	}
	if !result.Passed || result.Reason != "" {
		t.Fatalf("injected run did not pass: %+v", result)
	}
}

// TestRunOneCountsTurnsForInjectedChatter 验证计数包装器让 Expect.Turns 对
// 非 Scripted 的 provider 也生效：多轮调用被准确统计。
func TestRunOneCountsTurnsForInjectedChatter(t *testing.T) {
	// 第一轮请求工具，第二轮给出最终答案，共 2 轮。
	scenario := Scenario{
		Name:   "counted",
		Prompt: "do two turns",
		Expect: Expect{ToolCalls: []string{"ls"}, TextContains: []string{"done"}, Turns: intPtr(2)},
	}
	chatter := &recordingChatter{texts: []string{"", "all done"}}
	// 自定义 runner 直接驱动 workspace.Chatter 两轮，避免依赖脚本化回复的工具调用。
	run := func(ctx context.Context, sc Scenario, ws Workspace) (Trace, error) {
		var trace Trace
		if _, err := ws.Chatter.Chat(ctx, ws.Model, []llm.Message{{Role: "user", Content: ws.Prompt}}, nil, nil); err != nil {
			return trace, err
		}
		trace.Tools = append(trace.Tools, "ls")
		second, err := ws.Chatter.Chat(ctx, ws.Model, []llm.Message{{Role: "user", Content: "continue"}}, nil, nil)
		if err != nil {
			return trace, err
		}
		trace.Text = second.Content
		return trace, nil
	}

	opts := Options{ChatterFactory: LiveChatterAdapter(chatter)}
	result := runOne(context.Background(), 1, scenario, run, opts)
	if result.Turns != 2 {
		t.Fatalf("turns = %d, want 2", result.Turns)
	}
	if chatter.CallCount() != 2 {
		t.Fatalf("injected chatter calls = %d, want 2", chatter.CallCount())
	}
	if !result.Passed || result.Reason != "" {
		t.Fatalf("counted run did not pass: %+v", result)
	}

	// Expect.Turns 不匹配时应由包装器的计数触发失败。
	scenario.Expect.Turns = intPtr(3)
	result = runOne(context.Background(), 1, scenario, run, opts)
	if result.Passed || !strings.Contains(result.Reason, "expected 3 turns, the model was called 2 times") {
		t.Fatalf("wrong turn count was not rejected: %+v", result)
	}
}

// TestLiveChatterAdapterReturnsSameInstance 断言辅助构造的工厂为每个场景返回注入的同一实例。
func TestLiveChatterAdapterReturnsSameInstance(t *testing.T) {
	chatter := &recordingChatter{}
	factory := LiveChatterAdapter(chatter)
	if got := factory(Scenario{Name: "a"}); got != chatter {
		t.Fatalf("factory returned %T, want the injected chatter", got)
	}
	if got := factory(Scenario{Name: "b"}); got != chatter {
		t.Fatalf("factory returned %T for the second scenario, want the injected chatter", got)
	}
}

// TestRunOneDoesNotMutateScenario 验证注入路径不修改入参场景（含其切片与映射）。
func TestRunOneDoesNotMutateScenario(t *testing.T) {
	scenario := Scenario{
		Name:     "immutable",
		Prompt:   "p",
		Provider: []ScriptTurn{{Respond: Respond{Text: "ok"}}},
		Files:    map[string]string{"a.txt": "seeded"},
		Expect:   Expect{TextContains: []string{"ok"}, Turns: intPtr(1)},
	}
	before, err := json.Marshal(scenario)
	if err != nil {
		t.Fatalf("marshal scenario: %v", err)
	}
	opts := Options{ChatterFactory: LiveChatterAdapter(&recordingChatter{texts: []string{"ok"}})}
	_ = runOne(context.Background(), 1, scenario, fakeRun, opts)
	after, err := json.Marshal(scenario)
	if err != nil {
		t.Fatalf("marshal scenario after run: %v", err)
	}
	if !bytes.Equal(before, after) {
		t.Fatalf("runOne mutated the scenario:\n before: %s\n after: %s", before, after)
	}
}
